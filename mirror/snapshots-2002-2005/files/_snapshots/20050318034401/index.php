	<div align=justify><font class="storytext"><P>What do you get when you cross a former Material Girl with a fashion label that shouts out glam – a glam material girl? Well, not quite, but how about a chief executive with sophistication and fashion savvy?&nbsp; 
<P>Well, that’s apparently what <STRONG>Madonna</STRONG> is trying to portray in the new ad campaign for Versace’s spring/summer 2005. Or so says its creative director <STRONG>Donatella Versace</STRONG> in her exclusive e-mail interview with <I>StarTwo</I>.&nbsp; 
<P>
<TABLE cellPadding=7 width=124 align=left border=0>
