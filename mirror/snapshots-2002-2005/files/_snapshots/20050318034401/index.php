<DIV class=caption>Donatella Versace looking stylish in black. The idea of Madonna appearing in a Versace ad campaign happened during a dinner with Madonna, photographer Mario Testino and Donatella.</DIV></TD></TR></TBODY></TABLE>“Madonna represents a modern executive woman who has great style and flair,” says Donatella. “Not only is she in control of her career but also of her ‘fierce’ wardrobe.&nbsp; 
<P>“<STRONG>The advantage of using a celebrity like Madonna is that she becomes associated with our brand. This personification can in turn reinforce our brand image as well as the public perception. Her aesthetic image, style of life, values and what the celebrity communicates as a public person is capitalised and used towards the brand’s advantage</STRONG>.” &nbsp; 
<P>As for the ad campaigns, there is some confusion over what Madonna is supposed to represent. The theme is “women in the office” but what sort of woman is she? A secretary living beyond her means (hello, it’s Versace – how many secretaries not kept by the boss can afford the items?) or a stylish woman in a managerial position? Also, which CEO has to lick an envelope while kneeling on the carpet (however plush the carpet is)?&nbsp; 
<P>Why, a CEO that is represented ironically (cue: Alanis Morissette’s song), says Donatella. Hmm, right!&nbsp; 
<P>“The woman I have in mind when designing is one whose individuality and inner confidence shines on the outside. She is also sophisticated, sexy, smart and always dynamic and charismatic. The contemporary woman is not afraid to be a woman. She can still be powerful by keeping her femininity and sexiness.”&nbsp; 
<P>This does seem to be what Madonna represents or has been trying to portray herself all this while. It is a match made in designer and advertising heaven. It seems a sure thing and they have after all seen it work before when Madonna first appeared 10 years ago for Versace in the 1995 campaign.&nbsp; 
<P>There is also some continuity as the photographer then, Mario Testino, is the photographer now. Testino was already a noted fashion photographer then but the Kabbalah-practising Madonna was the first to specifically request that he be used. So now he is a celebrity in his own right and, according to Donatella, the two were joking and laughing during the shoot (they are old friends, after all). In fact, reveals Donatella, it was at the launch of Crystal Noir (the new Versace women’s fragrance) last October that Madonna had dinner with her and Testino and they broached the subject of the ad campaign and came out with the idea and Maddie agreed to appear on it.&nbsp; 
<P>The shoot was done in Westway Studio (which belongs to Testino) in London and it was completed in one day. It was reported that they wanted an office with lots of space but couldn’t find any (tsk, tsk, “crampy” London?). Spaces like that are apparently plentiful in Los Angeles, so they resorted to building a mock-up in the studio.&nbsp; 
