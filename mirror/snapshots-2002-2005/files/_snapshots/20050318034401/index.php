<P>“<STRONG>She (Lourdes) is very nice; she already loves fashion and dresses. Madonna is very sweet with her children</STRONG>.”&nbsp; 
<P>There were also some reports that Madonna complained about the cold and had to take breaks to do her Kabbalah thing. Nay, says Donatella. “<STRONG>We worked all day without having lunch. Madonna is very professional and wanted to check and overview every photo. She arrived perfectly on time and then we worked all day</STRONG>.”&nbsp; 
<P>Sigh, where have all the divas gone?&nbsp; 
<P>After all, adds Donatella, she and Madonna go way back (13 years) and Maddie was also a friend of Donatella’s late brother, Gianni. So, she says, there were no problems working with a good friend and it helped that they have worked together before. &nbsp; 
<P>“<STRONG>She’s a great artiste, an incredible woman and a fantastic mother</STRONG>,” affirms Donatella. When asked what Madonna would say about her, she replies: “Hopefully the same.”&nbsp; 
<P>Still, friendship is not cheap as the grapevine has conjectured that Madonna was paid US$10.5mil (RM39.9mil) although Donatella has refused to comment.&nbsp; 
<P>When all is said and done, what about the clothes then? (We think they are the main item, no?) &nbsp; 
<P>Well, there is a draped jersey dress split to almost the nether regions and gathered at the waist with a gold buckle – very nice. A shirt that shouts Versace and worn with body-hugging jeans or loose cream pants – very nice too. Strappy, strappy, sandals – excellent! And the bags, they are Versace – what more is there to say?&nbsp; 
<P>So, even though the platinum wig makes you do a double-take, the clothes win you over. They can make almost anyone look good and you don’t even have to resort to heavy touch-ups. Think about it.</P>
