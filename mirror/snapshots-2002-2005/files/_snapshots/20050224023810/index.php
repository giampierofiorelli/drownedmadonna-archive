<P><STRONG>Madonna is to lend two of her most cherished works of art to Tate Modern for an exhibition, it was revealed today</STRONG>.</P>
<P><STRONG>In June the Tate will hold the first ever British exhibition dedicated to Frida Kahlo</STRONG>. The eccentrically moustached Mexican painter was the subject of an Oscarwinning film Frida in 2002, starring Salma Hayek. The Tate Modern exhibition will star more than 70 of her 144 paintings - including Madonna's canvasses Self-Portrait with Monkey and My Birth. <STRONG>Madonna's art curator, <IMG src="http://images.thisislondon.co.uk/v2/showbiz/fridakahloST230205_100x140.jpg" align=left border=0>Darlene K Lutz, has said of the self-portrait: "The Kahlo painting is so powerful and enigmatic that we hope people will get beyond its personal history, as Madonna has, and see the artistic genius ... it is the number one love of her collection."</STRONG> Surrealist innovator Kahlo began painting in her teens as she convalesced after a road accident. Her work is rich in Mexican and Aztec imagery but is also autobiographical. The artist, who died in 1954, was married to fiery Mexican painter Diego Rivera, had an affair with Leon Trotsky and counted André Breton, Paulette Goddard and Sergei Eisenstein as close friends. Other landmark paintings in the show are The Little Deer, in which Kahlo paints herself as a wounded, hunted animal and The Two Fridas, one of her largest and most ambitious pieces. Self-Portrait with Monkey is one of the most cherished pieces in Madonna's art collection and has pride of place in her London home. The singer receives up to 10 requests a year to lend her works - which include paintings by Picasso, Léger, Salvador Dali and Man Ray. She presented Martin Creed with the Turner Prize in 2001 for his light bulb that switched itself on and off again. </P>
