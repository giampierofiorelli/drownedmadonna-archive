• Peter Rauhofer’s Live@Roxy4 includes <b>“Mother & Father”</b> by <b>Madonna</b>. The scorching hot Peter’s Reinvention Remix heavily filters and echoes Madonna’s vocals - “There was a time I believed I’d live forever…” - but they remain distinctly recognizable. Merging electro and classic club beats, the mix drops the drums about halfway through, allowing Madge’s voice to dominate. Initially a touch “cha cha carnival,” the build of pounding percussions layer ’80s electro and ’90s “Vogue,” creating a brilliant new millennium dance groove.<p>
