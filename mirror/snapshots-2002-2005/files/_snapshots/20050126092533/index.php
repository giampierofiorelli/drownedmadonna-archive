    <td background="images/bg.gif"><font class=""><a href="modules.php?name=News&new_topic=26">Exhibition</a></font><br><font class="testo_notizia" color="#000000"><b>Brad Elterman's Debut Photography Exhibition including Madonna.</b></font></td>
  </tr>
  <tr height="1">
    <td  background="images/riga.gif"></td>
  </tr>
  <tr>
    <td bgcolor="#FFFFFF">
	<div align=justify><font class="storytext"><P>California-born <STRONG>Brad Elterman</STRONG>’s first photography exhibition, <STRONG>"Like It Was Yesterday,"</STRONG> commenced with a star-studded opening night party on Wednesday, January 19th, 2005, at the <STRONG>Don O’Melveny Gallery</STRONG>, 9009 Melrose Avenue in West Hollywood, California. The exhibition will now remain on display, by popular demand, during normal gallery hours through Saturday, January 29th.&nbsp;&nbsp;<BR><BR><STRONG>The Elterman images present a regionally-focused collection of twenty-two photos (twenty black-and-white photographs and two in color), culled from his archives of the 1974 to 1984 era.</STRONG> The gallery exhibition’s subjects include Frank Sinatra, Michael Jackson, Bob Dylan, <STRONG>Madonna</STRONG>, Muhammad Ali, Mayor Tom Bradley, Dr. Jerry Buss, Jacqueline Kennedy Onassis, Hugh M. Hefner, Phil Spector, Joey Ramone, The Ramones, Joan Jett in her Runaways band at the legendary Tropicana Motel on Santa Monica Boulevard, and Steve Jones of the Sex Pistols.</P>
<P align=center><IMG alt="Madonna at the American Music Awards" src="/images/2005/brad_elterman/madonna01.jpg" border=0> <BR><EM>Madonna at the American Music Awards</EM><EM></EM> 
<P align=justify>"This grouping really documents the Los Angeles environment," says <STRONG>Elterman</STRONG>. "The editing process took a year and a half," explains Elterman. "I wanted photos that told a story, pictures that could be considered fine art. More than just a pop star with a guitar, which I had plenty of. I wanted to preserve a magical period -- from 1974 to 1984. <BR><BR>"The show really underscores the access I had to stars, musicians and actors. I have a photo of Michael Jackson after a party at Chasen’s. He was out there with a few photographers, and he only had one guy with him. He collaborated with us. Nowadays he would have sixty people around him, and you wouldn’t get the photo! <BR><BR>"In addition," <STRONG>Elterman</STRONG> continues, "in the last ten or twenty years, entertainment industry publicists have limited or prohibited access to their clients, and very generic poses and ’photo ops’ are the result. The PR people have taken the fun out of the scene and hampered the art. The photos I took in the ’70s and ’80s could never happen today." <BR><BR>"I covered the <STRONG>Oscars</STRONG> for fifteen years," <STRONG>Elterman</STRONG> confides, "but you won’t see any <STRONG>Oscar</STRONG> shots in the exhibition -- too boring and too publicist-driven." </P>
<P align=justify>"I’m also doing this gallery show to re-connect with friends, and the industry, and to help promote other photographers’ works from this era. I have a sense of something big happening in the fine art photography market. The iconic photos of the ’70s are going to be worth a lot of money. There’s a market for these images now, but I intend to develop a bigger market. <BR><BR>"Ultimately, the exhibition reflects some of the photographers who influenced my own work and style: Terry O’Neil, Bob Gruen, Diane Arbus, Ken Regan, and Richard Creamer, a close friend and mentor. Also Helen Levitt. She had this quality to capture the spark, the moment in people."&nbsp;</P>
<P align=justify>The gallery’s web address is <A href="http://www.omelvenygallery.com" target=_blank>www.omelvenygallery.com</A>, and Elterman’s site is at <A href="http://www.bradelterman.com" target=_blank>www.bradelterman.com</A>.</P>
