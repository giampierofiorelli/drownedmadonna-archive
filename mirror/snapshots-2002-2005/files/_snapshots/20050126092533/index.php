<P align=center><STRONG>Donatella Versace in Le Figaro</STRONG></P>
<P align=center><A href="http://www.madonnavillage.it/drownedmadonna/lefigaroversace.jpg"><IMG height=374 src="http://www.madonnavillage.it/drownedmadonna/lefigaroversace.jpg" width=500 border=0></A></P>
<P>- <STRONG>Jan 18- TREND- Exclusive for "Le Figaro", the interview of Donatella Versace who launches her advert campaign with Madonna.</STRONG> </P>
<P><STRONG>"The power is not incompatible with femininity" In ten days, the 8 photographs of the new advert campaign of Versace with Madonna will be published in the trend magazines around the&nbsp; world.</STRONG> </P>
<P>Photographed by <STRONG>Mario Testino</STRONG>, the American singer, as well-known for her 150 million albums sold in the world as for her eclectic tastes in trend, appears in it transfigured. At 46 years old, in jeans and printed shirt,in skirt and sweater with collar in V, in coktail dress and heels, Madonna incarnates, in an immaculate office, the "executive woman" of the XXI century.</P>
<P>&nbsp;<STRONG><EM>"Through this campaign, I want to prove that women can wear glamourous clothes to the office",</EM></STRONG> says the pop star. This quasi-proclamation in favour of the liberation of the behaviour of the woman to work is, as Donatella Versace explains below, deeper than what it seems at first.</P>
<P align=center><STRONG>&nbsp;Interview by Fabienne Reybaud LE FIGARO</STRONG>.</P>
<P>&nbsp;<STRONG>- Why&nbsp;did you choose Madonna for the next Versace campaign ?</STRONG> </P>
<P><STRONG>Donatella VERSACE</STRONG>. - Actually, <STRONG>it wasn't me who chose her, it&nbsp;was her</STRONG> ! Ten years ago, Madonna&nbsp; posed for one of our advert campaign for haute couture. <STRONG>Last autumn, after the launch of new Versace perfume, I met her again at a dinner, in London. Between pear and cheese, she said to me : <EM>" Why don't we make again an advert campaign together ?</EM></STRONG> " I thought that she was joking, but no. She was sure. </P>
<P><STRONG>What does she represent for you, what does she bring&nbsp;to you and to the mark ?</STRONG> </P>
<P>She is an icon, an innovating, revolutionary woman in her choices of life and career as in her style. Although she is very American, she adapts herself very easily to the place where she is. Madonna carries in herself a part of each country : Italian in Italy, English in England, with a more traditional look, with a touch of excentricity. Her intelligence, her sense of anticipation of the tendencies makes her&nbsp;that&nbsp; reinventing herself perpetually. <STRONG>To me, she symbolizes the woman of today, powerful, glamour and sure of herself. Madonna is a world model. She speaks to women of any condition, touches all the generations. She can bring only the best to Versace. </STRONG></P>
<P><STRONG>Why did you choose the theme of the woman at the office ?</STRONG> </P>
<P>Because it is the image of the modern woman. <STRONG>Madonna is a woman who works, me too, and my customers also. We have to stop thinking of the idea that an executive woman must wear a gray trouser suit to affirm her authority in a meeting of directors. Power is not incompatible with femininity. And don't care if this destabilizes some men</STRONG>. The important thing is that women go ahead. </P>
<P><STRONG>Madonna's contract for this advert campaign would be about 10 million dollars...</STRONG> </P>
<P>People say anything. That makes me smile. The only thing that I can say to you is that in terms of image and sale the repercussions will be more than excellent. Moreover, the 1995-1996 winter campaign with Madonna had had a very strong impact. It showed that a young woman, modern and sensual could be a customer of haute couture and for Versace. In 2005, the Versace style has evolved. The proportions changed, the look was purified<STRONG>, clothing is adapted to the urban life of active women who do not want therefore to renounce to the glamour</STRONG>. </P>
<P>Legend of photo of Madonna : Perfect synthesis between power and glamour, Madonna incarnates the next advert campaign of Versace. She wears a skirt (577 euros), a sweater collar V (547 euros) and sandals (525 euros) of the spring/summer collection 2005. (Photograph: Mario Testino. Designer: Brana Wolf. Hairdresser: Andy Lecompte. Make-up man: Tom Pecheux.) </P>
