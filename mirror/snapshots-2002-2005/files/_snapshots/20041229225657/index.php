    <td background="images/bg.gif"><font class=""><a href="modules.php?name=News&new_topic=6">Magazines</a></font><br><font class="testo_notizia" color="#000000"><b>[<a href="modules.php?name=&amp;file=categories&amp;op=newindex&amp;catid=10"><font class="esclusiva">BREAKING NEWS</font></a>] Madonna talks about The English Roses Sequel and Movie</b></font></td>
