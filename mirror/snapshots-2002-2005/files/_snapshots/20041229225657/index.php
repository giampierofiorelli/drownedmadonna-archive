  <tr>
    <td bgcolor="#FFFFFF">
	<div align=justify><font class="storytext"><P>As our readers remember, <STRONG><A href="http://www.drownedmadonna.com/index.php">DrownedMadonna</A></STRONG> revealed in a<STRONG> World Exclusive </STRONG>article<STRONG> ( </STRONG><A href="http://www.drownedmadonna.com/modules.php?name=News&amp;file=article&amp;sid=5202"><STRONG>READ HERE</STRONG></A><STRONG>) </STRONG>, <STRONG>Madonna's French promotion</STRONG> for the <STRONG>"The Adventures of Abdi"&nbsp; ,&nbsp; we also &nbsp;announced that the book</STRONG> will be&nbsp;out in France&nbsp;in <STRONG>March&nbsp;2005.</STRONG></P>
<P>We talked you about <STRONG>an interview</STRONG> run by&nbsp;<STRONG> Version Femina a magazine</STRONG>&nbsp;&nbsp;in circulation with several French regional newspapers.</P>
<P><STRONG>Madonna's interview is featured in this week 's issue of Version Femina available in stores now</STRONG>.</P>
<P align=center><A href="http://img157.exs.cx/img157/926/versionfeminacover1nd.jpg"><IMG height=547 src="http://img157.exs.cx/img157/926/versionfeminacover1nd.jpg" width=400 border=0></A></P>
<P align=center><STRONG>[click to enlarge]</STRONG></P>
<P><STRONG>Madonna</STRONG> talks&nbsp;to journalist <STRONG>Anne Michelet</STRONG> about <STRONG>one</STRONG> of her<STRONG> new</STRONG> projects , "<STRONG>The English Roses</STRONG>" Movie and <STRONG>the sequel</STRONG> to the E.R.book.</P>
<DIV><FONT size=2>
<DIV><FONT color=#0000ff>LADY MADONNA</FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>An energetic and intelligent blue glance, an elegant blond silhouette in a wise tailor trousers... the star is impressive. But it's Madonna, mother and author of children's books, who welcomes us, smiling, at her editor's office in London. An exclusive ! </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><BR><FONT size=2><STRONG>Have you always been attracted by writing ?</STRONG></FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>Yes. At school, my favourite teacher was the English literature one. She taught me the love for the language, reading and how to use my imagination. She inspired me for <STRONG>"Mr Peabody's Apples</STRONG>". I wrote also poems with my sister when I was young, and I loved to read poetry. I was obsessed by <STRONG>Sylvia Plath</STRONG>... (American poetess and novelist, 1932-1083). Then I kept going with songs lyrics, and then today, with children's stories. It looks like a natural evolution to me. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Where do you find inspiration for these stories, all so differents ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>I was upset by those eternal stories of princes and princesses where nothing never happens. I wanted to talk about conflicts that we all have with ourselves, that we face and that we overcome. In<STRONG> The English Roses</STRONG>, you find envy, jealousy and the message that you shouldn't judge people on their appearance. I inspired myself a bit from my daughter, Lourdes, who goes to a French school in London and suffers often of the jealousy of her little pals. My second book, Mr. Peabody's Apples, evokes the power of words, the idea that what we say can be positive or negative for others. Yakov and the Seven Thieves talks about the prayer and our possibility to make miracles happen. It is very interesting to understand how every character is going to overcome a problem and succeeding in something.</FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>The fourth book, "The Adventures of Abdi", will be out in March in France...</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>It is about the certainties, on the way you deal with obstacles that you need to turn into positive experiences in order to grow up. And at last, the fifth and last book of this series of tales, Lotsa de Casha, will have as its theme the giving and the sharing, because it will tell the life of a very rich Italian who lives in a shiny glittering castle and beleives he can buy anything. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Are your children your first public ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>Oh yes! I tell them my stories because they are very open-minded, then it's my husband's turn, who is more critic. Reading a story to Lourdes and Rocco, at the hour of going to bed, is the best moment to transmit to them something about life, love, and research of happiness. My daughter's approval is, at my eyes, essential. While I'm outlining a story and I'm telling her about it, I see immediately when her attention is gone... That means that I must work again... (Laughs). </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>And how does react your husband ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>He had a certain influence on the last story, Lotsa de Casha. The problem is that as a good English man he is not fond of sentiments, then, sometimes, we disagree and quarrel... In conclusion, I tell him : "Thank you very much, but I'm going to write the book like I want to do it !" (Laughs) </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Does writing require a lot of work ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>A lot, but I also enormously enjoy it. It's a real challenge ! Every story happens in a different century, in Eastern Europe, in England, in Saudi Arabia, in America... Fashion changes, technology changes, architecture changes, transports change, but the relationships between people never change... Therefore, every book shows the universal of themes that exist since the creation of humanity. I always mix moral and humor in them.</FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Is that the reason of your dedication "and also for parents" ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>Exactly. My stories are always in the perfect continuation of the "human lessons" that we received from our ancestors, they show the importance of love between human beings. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Perfectionist, did you also look after the illustrations ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>Yes, all of them. Every page, every detail ! I made everyone crazy, to begin with the artists from all over the world who came to illustrate these tales... (Laughs) Sorry ! But the result is there, because the drawings are really awesome. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Little girl, which were your favourite books ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>The loss of mother's love made me very sad (Madonna lost her mother when she was five years old) and I escape in reading. One of my favourite books was a French one : "Le Petit Prince" ("The Little Prince"), by Saint-Exupéry. I especially remember one sentence that impressed me : "... you only see well with the heart. The essential is invisible for the eyes." I also loved very much the textes of Lewis Carroll, like "Alice aux pays des merveilles" ("Alice in Wonderland"). I can't remember all the books I read, but I've always been - and I am always - a great reader. I admit I use to have the annoying attitude of reading two or three books at the same time. I should correct myself, but... </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Are you still interested in writing ?</STRONG> </FONT></DIV>
<DIV><FONT size=2><STRONG>I wrote the&nbsp;sequel to&nbsp;the English Roses, and we are currently working on the <FONT size=2>illustrations. <FONT color=#ff0000>Lourdes wanted&nbsp; a boy to be in ,&nbsp;so we invented a Spanish </FONT></FONT><FONT size=2><FONT color=#ff0000>student, Dominique de la Guardia. </FONT>There is also one brilliant professor and twins, </FONT><FONT size=2>tap dancers, Bunny Love and Candy Darling. I added a lot of characters&nbsp;to wrap up&nbsp;</FONT><FONT size=2>the intrigue, because I would like to make a movie of it in which a </FONT><FONT size=2>lot of things will happen.<FONT color=#ff0000> I will reserve myself the voice of the fairy godmother of the small </FONT></FONT><FONT size=2><FONT color=#ff0000>girls</FONT>, after all&nbsp;it is a&nbsp;bit of what I am in this story</FONT></STRONG></FONT></DIV>
<DIV><BR><FONT size=2><STRONG>Did you expect such a worldwide success ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>No, not at all. You know, I had never written children's books, so it was a very nice surprise to see that the&nbsp;people loved them. It's an amazing experience, because my stories are translated in thirty-eight different languages in more than one hundred and ten countries and we also have an edition in braille. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>You are donating the income of the books' sales to some charities for children. Would you like to work with Unicef ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>Maybe. I think of Audrey Hepburn, who I admire a lot and who is a model for me. What she has done in her life was extraordinary, and she used her celebrity in a positive way. We are not in the spotlight for no reason, and we have to take this opportunity to make things better in our world. As opposed to what a lot of people thought at the beginning, I don't write to become richer, but to share with children and adults the experience and the wisdom that I acquired becoming a mother. Motherhood has been somehow a liberating experience for me, and I put all of my heart and soul in these books. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Speaking of that, what kind of mother are you ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>Hum... a good one, I hope. A bit funny too, despite I'm also quite strict at home and that&nbsp; fixe the limits. You know, I am the naughty policeman, as opposite to my husband. I am the one who imposes the rules and he is the one who breaks them ! For example, if I say : "It's time to go to bed" or "The icecream&nbsp;is for the after dinner, not before", Guy comes and messes everything up. (Sighs) But don't worry, I adore to party with Lourdes and Rocco. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>Your daughter has just finished writing a story, was it under your suggestion ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>No, it wasn't. I encouraged her to dance, but never to write. She came and asked me if I wanted to write a story for a charity association who fights against cancer. I answered to her that I had a million things to do, and Lourdes decided then to do it herself. I told her : "Ok, super, go ahead." And she has been published in a book which collects as well stories by the Duchess of York, the singer Katie Melua and other celebrities. My Lola is incredibly talented ! I don't know where it comes from... </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2><STRONG>You look particularly serene. What is your secret ?</STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><FONT size=2>I don't know, because I think I don't sleep enough and that always worries me !(Laughs). But seriously, I am more serene today, because I am happy in my life, with my husband and my children. </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
<DIV><BR><FONT size=2><STRONG><U>Interview by Anne Michelet</U></STRONG> </FONT></DIV>
<DIV><FONT size=2></FONT>&nbsp;</DIV>
