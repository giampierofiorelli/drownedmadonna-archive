<div align=justify><font class="posted" color="#000000"><DIV class=subhead><B><IMG src="http://iparenting.com/graphics/madonna.jpg" align=left border=0>It's not what she wears, but how she wears it that has made the pop singer an idol for two decades</B> </DIV>
<DIV class=byln>Wednesday, August 04, 2004 
<DIV>Evelyn Theiss</DIV><B>Plain Dealer Fashion Editor</B> </DIV>
<P><STRONG>It's been 21 years since</STRONG> the belly-baring, headband-wearing street urchin with the improbable name of Madonna burst onto the pop music stage. </P>
<P><STRONG>Two decades later, she is still in the international spotlight. She has evolved from Madonna, the pop tart, to Madonna, the S&amp;M sex maven, to Madge the British wife/children's author, to Esther, the Kabbalah follower</STRONG></P>
<P>The adult life of the Bay City, Michigan-born Madonna Louise Veronica Ciccone has been a spinning top that has generated love and awe (from her fans), hate and disgust (from those who found her merely vulgar) and controversy (enough to fill a book). </P>
<P>Whatever else was going on, though, Madonna and the world of fashion have been inextricably tied together. She has hooked up with designers such as <STRONG>Versace, Dolce &amp; Gabbana and Jean-Paul Gaultier</STRONG> (maker of her famous pointy corset bra), to name just a few, and given them name recognition in new circles. </P>
<P>Most people, in fact, were more likely to wonder what Madonna's latest look would be blond Marilyn? brunette Goth? and so on than how her latest single would sound. </P>
<P>"Her image was always more cutting edge than her music," says <STRONG>Anne Bissonnette, curator of the Kent State University Museum.</STRONG> "It was so strong, that, from the start, you could immediately recognize her followers." </P>
<P>And how's this for irony? <STRONG>The woman who made underwear worn as outerwear famous was recently named the best-dressed woman over 40 in Great Britain, by no less than that country's Good Housekeeping magazine</STRONG>. </P>
<P>Well, it could never be said that Madonna's fashion range isn't extraordinarily wide. </P>
<P>She may have worn prim, flowered<STRONG> Prada</STRONG> dresses on her book tour, but on her current concert tour she wears costumes by made by <STRONG>Karl Lagerfeld, Stella McCartney and Christian LaCroix </STRONG></P>
<P>That tour features a retrospective of her various looks over the years: from the white lingerie bride look, to pointy-breasted dance warrior, to kilt-wearing schoolgirl run amok. </P>
<P><STRONG>Like a virgin </STRONG></P>
<P>with shock appeal </P>
<P><STRONG>David Wolfe is one of the world's top fashion forecasters, so he's been paying attention to Madonna, he says, "since when she was Like a Virgin. ' " </STRONG></P>
<P><STRONG>Wolfe, creative director of New York's Doneger Group, first saw her on MTV in the mid-1980s. </STRONG></P>
<P><STRONG>"We were so easily shocked then," he says. "Her wearing a lacy white bra as an outer garment that was just the beginning of what I think of as an endless succession of what has inspired fashion." </STRONG></P>
<P>Earlier in her career, Madonna said, "I think I have an original sense of style, and I think that people are unconsciously copying my style. Sometimes, when you see people do that, it's really cute, you know? But sometimes it isn't." </P>
<P>Or, as Wolfe adds dryly, "I'm not sure it's been a great 20 years as far as fashion.<STRONG> She's one of the people who have helped push down the fashion taste level, since she always had to be top banana in the shock department." </STRONG></P>
<P>But, he acknowledges, "She also was one of the first pop stars to link herself with top fashion names, and she led pop music into high fashion." </P>
<P>Now, of course, one typically sees Beyonce, Christina Aguilera and other pop singers wearing designs by Versace and Dior. </P>
<P><STRONG>Tom Julian, the New York- based trend analyst for Fallon Worldwide, says Madonna's background in New York City's "underground" was crucial to her becoming someone who popularized trends, including bringing fetish wear out of the closet. </STRONG></P>
<P>"She had that vantage point and an instinct for how exciting that world was," he says. "She had the mind to extract certain elements from it and to make those elements commercial, relevant and exposed." </P>
<P>Her timing was right, too. Madonna became, and stayed, a star just as fashion designers were themselves becoming celebrities. </P>
<P>"<STRONG>She came of age in a vibrant fashion era," says Julian. "She embraces the fashion darlings designers like Dolce &amp; Gabbana and not only for her concerts. She wore Olivier Theyskens at the Oscars one year and made him a name in fashion." </STRONG></P>
<P>Bissonnette was in fashion school when Madonna emerged in the mid-1980s. </P>
<P>"Jean-Paul Gaultier was important before, but she sent him to new heights," says Bissonnette. <STRONG>"She had a great ability to select individual designers who had a focus on performance- based garments. </STRONG></P>
<P>"With Madonna it was always as much about how she wears the clothes, as it is about the clothes themselves." </P>
<P><STRONG>Expressing herself</STRONG> </P>
<P>over and over again </P>
<P>At first, Madonna mimicked the look of New York's fringe, artsy world: the raggedy, layered thrift-shop look, complete with black leather jacket, multiple rubber bracelets and torn fishnets. Later, her fashion turns were more stark, whether in the androgynous oversized tuxedo in the "Express Yourself" video or as the Hollywood bombshell in her Dick Tracy phase. </P>
<P>But more often than not, Madonna mixed things up. "She appropriated pieces from different designers," Bissonnette explains. In other words, she was never like Cher, who always wore Bob Mackie for big public occasions. </P>
<P>"A bustier is a bustier, but with a crinoline skirt and a funky hairstyle, it becomes something else," adds Bissonnette.Then too, there was her body, which evolved from puppy-fat softness, to articulated musculature to a longer-muscled yoga look.&nbsp;<STRONG> "The difference between fashion and style is one's ability to do that, and that's what Madonna has." </STRONG></P>
<P>Bissonnette points out that Madonna's style incorporated her body. She brought an extreme muscular look into the mainstream. "It became OK to look like that," Bissonnette says. </P>
<P>Still, while Madonna might inspire fashion followers, Wolfe says, "I never saw her wearing something first. She'd pick something up, from streetwear, or often, she'd just be wearing an extreme version of something that's come down the runway." </P>
<P>Where she has excelled, he says, "was making the general public aware of trends that otherwise only fashion people were aware of. </P>
<P>"<STRONG>She feels the pulse of fashion she gets it a heartbeat ahead of the general public." </STRONG></P>
<P><STRONG>Bissonnette agrees. "She is not a follower, but a leader. It's very hard to maintain that for 20 years, but she has done it."</STRONG> </P>
<P>Wolfe says Madonna is the per fect icon for a population with a short attention span. </P>
<P><STRONG>"She understood that fashion was speeding up and she encouraged people to change constantly. She never stayed the same long enough for anyone to get bored with her." </STRONG></P>
