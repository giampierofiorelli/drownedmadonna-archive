	<div align=justify><font class="storytext"><P><IMG src="http://www.nynewsday.com/media/photo/2005-03/16687161.jpg" align=right border=0><STRONG>Madonna</STRONG>, the Ramones, the Pretenders, Talking Heads, the Smiths, Depeche Mode, Climax Blues Band, K.D. Lang&nbsp;and hundreds more all got their starts in the music business thanks to <STRONG>Seymour Stein</STRONG> and his famed <STRONG>Sire Records</STRONG> label.</P>
<P><STRONG>Tonight</STRONG>, <STRONG>Stein</STRONG> will&nbsp;step into the spotlight for the evening to be inducted into the <STRONG>Rock and Roll Hall of Fame</STRONG> for his achievements in furthering the music he loves. <STRONG>Stein</STRONG> joins his discoveries the Pretenders along with U2, Buddy Guy, Percy Sledge, the O’Jays and Premier Talent Agency founder Frank Barsalona in the hall’s inductee Class of 2005.</P>
<P>"Rock and roll has been my life - the whole explosion in rock music, I lived through it," <STRONG>Stein</STRONG> said. "I still love what I do and I love the <STRONG>Hall of Fame</STRONG>. I helped start it, but I didn’t think I would be inducted at this point. It’s a bit surreal in a way. <STRONG>There are so many people who should be inducted before me</STRONG>."</P>
<P>Stein said he will always keep looking for great songs. "I heard them with the Ramones. I heard them with <STRONG>Madonna</STRONG>," <STRONG>Stein</STRONG> said. "<STRONG>When I make up my mind about a band, 85 percent of it is about the songs and 15 percent is about everything else</STRONG>. I’m a song man - that’s what I am." </P>
