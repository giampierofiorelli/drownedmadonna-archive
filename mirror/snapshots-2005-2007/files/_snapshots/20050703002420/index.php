<P>It was a really strange feeling to be around thousands of <STRONG>Madonna-fans</STRONG> as a change to being the only one as I was back home, and I was pleased when I heard the music playing in the speakers. <STRONG>"All Around The World"</STRONG> with <STRONG>Lisa Stansfield</STRONG>. I knew that the extremely popular band <STRONG>Technotronic</STRONG> (<STRONG>"Pump Up The Jam"</STRONG>, if you remember?) was <STRONG>the warming up act</STRONG>, so I thought nothing could ruin my day. TWO great acts in one evening. It felt like Christmas, until <STRONG>a Swedish guy got up on the stage and told us that Technotronic couldn´t come, and instead the Swedish group Fingerprints would warm us up</STRONG>. <BR>Warm up? More cool us down, was my thoughts, and many others. They were a typical 80´s pop-rock band with songs that went in one ear and out the other. <BR><BR><STRONG>As you can see on the photo above taken from a helicopter, there was hardly any place with shadows, and the sun was really burning that day</STRONG>. So was the crowd. The Swedish guy pleaded over and over with the people right in front of the stage to stop pushing. It´s called The European Phenomena, and is one of the reasons to why I avoid the fence in front of the stage. Who wants to be crushed? (<STRONG>Even Madonna herself had to tell the audience to stop pushing a couple of times</STRONG>, so it must have been bad for the poor people at the front since <STRONG>Madonna</STRONG> usually never has to stop a concert like that). <BR><BR>As we waited for her we went through a long <STRONG>30minutes of Fingerprints</STRONG>... <STRONG>Madonna herself had dinner, a massage and flipped through a Swedish magazine insert devoted to her that included quick questions to people on the street</STRONG> (what´s your favourite Madonna song, what would you say to her if you met her, and so on). <STRONG>And she was very curious about what Swedes said about her, according to Liz Rosenberg who chatted with a journalist who got back stage</STRONG>. <STRONG>Earlier that day she had been on the daily jogging tour with five body-guards around her</STRONG>. <BR><BR><A href="/images/2005/svezia/blond/01.jpg" target=_blank><IMG src="/images/2005/svezia/blond/02_small.jpg" align=left border=0></A>We in the audience cheered with joy as <STRONG>Fingerprints</STRONG> left the stage and prepared for at least <STRONG>30 minutes</STRONG> before <STRONG>Madonna</STRONG>´s arrival on stage, but <STRONG>we were wrong</STRONG>... </P>
<P><STRONG>They cleared the stage from Fingerprint´s instruments, and before we could say Good, the roaring sound of the intro started to play at 8.15 pm. People screamed and ran towards the stage, and everyone held their breath</STRONG>. The monument we all had waited for for three months was finally here. We was finally going to see <STRONG>Madonna</STRONG>, in the flesh! </P>
<P align=justify><STRONG>Madonna</STRONG> greeted us with the words <STRONG>"Alright Sweden, I just wanna know one thing: Do you believe in love? Cause I got something to say about it"</STRONG> and then bursted into <STRONG>Express Yourself</STRONG>. <BR><BR>The concert was a thrill to watch. The arrangements, the dancers, and the feeling of being at the same place as <STRONG>Madonna</STRONG>. I, who was <STRONG>14</STRONG> at the time, got hysterical when she said <STRONG>Tack</STRONG> (<STRONG>thank you</STRONG>) after <STRONG>Hanky Panky</STRONG>. "I can´t believe it! She spoke <STRONG>Swedish</STRONG>!" My uncle and his girlfriend smiled at me and calmed me down by pointing out that it was <STRONG>just ONE word</STRONG> that she said in <STRONG>Swedish</STRONG>... I ignored their remark and continued on watching the show. <BR><BR><STRONG>Sweden</STRONG> is a Scandinavian country. We are known for the <STRONG>midnight sunshine</STRONG> in the northern part of our country, and in the summer we have <STRONG>nearly 18 hours of daylight</STRONG>. This meant that <STRONG>Madonna had the rare experience of perforning almost an entire concert in daylight which, she later said, felt very strange</STRONG>... </P>
<P align=center><A href="/images/2005/svezia/blond/03.jpg" target=_blank><IMG src="/images/2005/svezia/blond/03_small.jpg" border=0></A></P>
<P align=justify>After <STRONG>Vogue</STRONG> my company and I started to move towards the exit before everybody came. It took some time since I desperately wanted a tour souvenir. The over-sized and luxuarus programme was too expensive for me, but I got a poster, which now is framed and hanging over my bed. (it´s the black and white "<STRONG>Strike-A-Pose</STRONG>"). </P>
<P align=center><A href="/images/2005/svezia/blond/04.jpg" target=_blank><IMG src="/images/2005/svezia/blond/04_small.jpg" border=0></A>&nbsp;<A href="/images/2005/svezia/blond/01.jpg" target=_blank><IMG src="/images/2005/svezia/blond/01_small.jpg" border=0></A></P>
<P align=justify>The sun started to set and the last thing I saw before <STRONG>Madonna</STRONG> went off stage was <STRONG>Keep It Together</STRONG>, with the light-show intended for the number. The bus was on a hill, so I saw it from that hill, and it was sooo beautiful. <STRONG>I will never forget the sight of the enormous crowd listening to Madonna singing the last bit acapella</STRONG>... </P>
<P align=center><IMG src="/images/2005/svezia/blond/poster.jpg" border=0>&nbsp;&nbsp;<IMG src="/images/2005/svezia/blond/MadonnaPer.jpg" border=0> 
<P align=justify>We were <STRONG>55.000</STRONG> watching theshow at <STRONG>Eriksberg</STRONG>. <STRONG>Excluding all the boats that was floating around...</STRONG> </P>
<P align=justify>On the right side of the crowd-picture above there is a hill, and on top of that hill there was a big building with tons of afficies, and everyone who worked there "worked overtime" that night. Every window was open and full of people. </P>
<P align=justify>The busride home was long and tiresome, but I was smiling the whole way. <STRONG>I had seen Madonna live in concert, and just between you and me, nothing has beaten that feeling</STRONG>... </P>
