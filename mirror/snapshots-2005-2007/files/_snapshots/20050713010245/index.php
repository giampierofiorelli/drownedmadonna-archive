	<div align=justify><font class="storytext"><P>THE sinewy, contorted image of Madonna, naked and squatting over a grave, caused outrage when it was unveiled, not least to the singer herself. </P>
<P>But if the star believed she and the world had seen the last of Peter Howson's deeply unflattering portraits, she was wrong. </P>
<P>Just three years after Howson's Madonna paintings were exhibited in Ayr - and shortly afterwards snapped up by collectors - two of them are coming up for sale in a very public auction at Sotheby's. </P>
<P>Such is the notoriety of the paintings, the auction at Gleneagles next month is expected to attract interest from a horde of international collectors who are expected to bid at least £30,000 for the pair. </P>
<P>Madonna was once among the celebrity collectors of Howson's works, but made no secret of her dislike for his paintings of her, and condemned him as a voyeur and self-publicist. </P>
<P>The first painting, an oil, titled Portrait of Madonna 2002, shows the pop star standing against a red background with a transparent top revealing her breasts against a muscular, sinewy torso. It is expected to achieve more than £30,000. </P>
<P align=center><IMG height=336 src="/public/PeterHowsonMadonna2.jpg" width=503 border=0></P>
<P>The second painting, a watercolour based on Howson's infamous portrait, Death and Madonna, shows the singer squatting naked in a graveyard. Sotheby's expects it to fetch around £10,000. </P>
<P align=center><IMG height=403 src="/public/PeterHowsonMadonna.jpg" width=286 border=0></P>
<P>Last night Howson, who said he produced the paintings from "memory and imagination", admitted his once close friendship with the singer was unlikely to be rekindled because of the sale. </P>
<P>Asked if he thought the upcoming sale will reopen old wounds, Howson replied: "Maybe." He added: "I haven't heard a thing from Madonna since I held the exhibition in Ayr. I don't know whether she is not interested in me any more or she's fallen out with me or whatever. </P>
<P>"There are other people that are interested in my work now so I have forgotten about Madonna. But maybe she will buy one. She bought a picture of a boxer for Sean Penn but she lost that when they were divorced. But since then she has bought a number of my paintings. </P>
<P>"Madonna is a fascinating woman. I originally painted her because she collected my art. I remember she was quite difficult to paint as conventionally beautiful people are more difficult than ugly people." </P>
<P>Scotland On Sunday art critic Iain Gale said the arrival of the paintings in the public arena could rekindle the controversy. </P>
