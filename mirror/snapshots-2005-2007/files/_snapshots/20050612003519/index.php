	<div align=justify><font class="storytext"><P class=byline><SPAN>By Mark Shanahan, <STRONG>Globe Staff &nbsp;|&nbsp;</STRONG></SPAN><STRONG> <SPAN class=date>June 9, 2005</SPAN></STRONG></P>
<DIV class=hidePages id=articleGraphs>
<DIV class=showPage id=page1>
<P><STRONG>Every couple of years, Madonna reemerges</STRONG>. Sometimes it's with a CD; sometimes it's with a movie; sometimes, unfortunately, it's with a fragrance. This time, the 46-year-old expatriate pop star is back with a children's book, her fifth in the past three years. If there was any doubt, the black-clad boy toy who squirmed so memorably on MTV 20 years ago is long gone. As one wag wrote recently, Madonna has become Mamadonna. The superstar singer lives happily in England these days with her director husband, Guy Ritchie, and her two children, Lola and Rocco.</P>
<P>But this week, Madonna is in New York, doing what she does better than just about anybody else -- publicity. Reached by telephone yesterday, she took a few minutes to chat about her new book, parenting, recording, and of course, religion.</P>
<P><EM>Why are you doing press? Aren't there millions of people who'll buy whatever you do?</EM></P>
<P>Are you kidding? No way. I still have to make an effort. <STRONG>You're being incredibly presumptuous and naive to think that people just run and get whatever you do.</STRONG></P>
<P><EM>So you don't think that way.</EM></P>
<P>Hell, no.</P>
<P><EM><STRONG>Hell, no?</STRONG></EM></P>
<P><STRONG>Yes. . . . I'm still a girl from Michigan.</STRONG></P>
<P><EM>How much time do you spend actually writing?</EM></P>
<P>Haven't been writing books lately, because I've been busy recording. But when I am writing, I set time aside, maybe four hours in the afternoon, when it's quiet and my kids are at school. I sit at my computer, and I have this little statue on my desk. . . . She's a kneeling woman who's got her eyes closed, and she's very meditative. She's my muse.</P>
<P><EM>If you're not writing or recording, what does your day look like?</EM></P>
<P>There's always the bit where I have to get my butt out of bed in the morning. (Laughs.) That's at 7:15 a.m. I wake up, go downstairs, have breakfast with my kids, and argue with my daughter about combing her hair. Then I get them off to school. Sometimes I take them, but it's not my favorite thing to do, let's be honest. I don't like the whole getting up and make myself look presentable for school routine.</P>
<P><EM>Tell me about motherhood. You like it? Is the idea better than the reality?</EM></P>
<P>Isn't the idea of everything better than the reality? No, actually, I love it. My children aren't with me right now, and I miss them terribly. They fill up my life. I don't know where I'd be without them.</P>
<P><EM></EM></P>
<P><EM>It's hard to talk about your children's books without at least mentioning your rather notorious first book (<STRONG>1992's picture book</STRONG> <STRONG>''Sex").</STRONG> You've said it was a different time. <STRONG>Does that imply regret?</STRONG></EM></P>
<P><STRONG>No, no. You know me better than that. I don't regret it.</STRONG> What's the point of regretting anything you've done? If I didn't do everything I did, I wouldn't be who I am now.</P>
<P><EM>Good Point<IMG src="http://images.news.com.au/thedailytelegraph/3258895_madgeweb.jpg" align=right border=0></EM></P>
<P>I &nbsp;mean, so I took my clothes off for a few pictures. That's the norm now.</P>
<P><EM>You have to put your clothes on to get attention these days.</EM></P>
<P><STRONG>That's what I'm doing. (Laughs)</STRONG></P>
<P><EM>Tell me about your religious beliefs.</EM></P>
